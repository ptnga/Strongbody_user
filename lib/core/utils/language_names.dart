/// (web `languageNames`). Giá trị đã là tên (title bảng languages) hoặc mã lạ → giữ nguyên.
String languageLabel(String value) {
  final raw = value.trim();
  if (!RegExp(r'^[a-zA-Z]{2,3}([-_][a-zA-Z0-9]{2,4})?$').hasMatch(raw)) {
    return raw;
  }
  final code = raw.toLowerCase().replaceAll('_', '-');
  return _languageNames[code] ?? _languageNames[code.split('-').first] ?? raw;
}

